package com.example.kinetiq.utils

import android.content.Context
import android.content.Intent
import android.graphics.Color
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import androidx.core.content.FileProvider
import com.example.kinetiq.ui.workout.WorkoutDayUi
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object WeeklyPdfExporter {

    fun generateAndShareWeeklyPdf(
        context: Context,
        userName: String,
        splitTitle: String,
        weeklyPlan: List<WorkoutDayUi>
    ) {
        val document = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page = document.startPage(pageInfo)
        val canvas = page.canvas

        val titlePaint = Paint().apply {
            color = Color.parseColor("#0F1115")
            textSize = 20f
            isFakeBoldText = true
        }

        val headerPaint = Paint().apply {
            color = Color.parseColor("#00E676")
            textSize = 14f
            isFakeBoldText = true
        }

        val textPaint = Paint().apply {
            color = Color.parseColor("#333539")
            textSize = 12f
        }

        val dateStr = SimpleDateFormat("MMMM d, yyyy", Locale.getDefault()).format(Date())

        var y = 50f
        canvas.drawText("KINETIQ AI FITNESS — WEEKLY SUMMARY REPORT", 40f, y, titlePaint)
        y += 24f
        canvas.drawText("Athlete: $userName | Date: $dateStr", 40f, y, textPaint)
        y += 18f
        canvas.drawText("Program Split: $splitTitle", 40f, y, textPaint)
        y += 30f

        val completedSessions = weeklyPlan.count { it.isComplete }
        val totalSessions = weeklyPlan.size
        val totalSets = weeklyPlan.sumOf { it.totalSets }
        val completedSets = weeklyPlan.sumOf { it.completedSets }

        canvas.drawText("WEEKLY PERFORMANCE SUMMARY", 40f, y, headerPaint)
        y += 20f
        canvas.drawText("Sessions Completed: $completedSessions / $totalSessions", 40f, y, textPaint)
        y += 16f
        canvas.drawText("Total Volume Sets Completed: $completedSets / $totalSets sets", 40f, y, textPaint)
        y += 30f

        canvas.drawText("EXERCISE BREAKDOWN BY DAY", 40f, y, headerPaint)
        y += 24f

        weeklyPlan.forEach { day ->
            val statusStr = if (day.isComplete) "[COMPLETE]" else "[${day.completedSets}/${day.totalSets} sets]"
            canvas.drawText("${day.dayName} — ${day.title} $statusStr", 40f, y, textPaint)
            y += 16f

            day.exercises.forEach { ex ->
                canvas.drawText("   • ${ex.name} (${ex.sets} sets × ${ex.reps} reps)", 55f, y, textPaint)
                y += 14f
            }
            y += 8f

            if (y > 780f) return@forEach
        }

        y += 20f
        canvas.drawText("Generated by Kinetiq AI Fitness & Diet Coach", 40f, y, textPaint)

        document.finishPage(page)

        val pdfDir = File(context.filesDir, "pdfs").apply { if (!exists()) mkdirs() }
        val pdfFile = File(pdfDir, "Kinetiq_Weekly_Summary_${System.currentTimeMillis()}.pdf")

        try {
            pdfFile.outputStream().use { out ->
                document.writeTo(out)
            }
            document.close()

            val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", pdfFile)
            val shareIntent = Intent(Intent.ACTION_SEND).apply {
                type = "application/pdf"
                putExtra(Intent.EXTRA_STREAM, uri)
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            }
            context.startActivity(Intent.createChooser(shareIntent, "Share Kinetiq Weekly PDF Report"))
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }
}